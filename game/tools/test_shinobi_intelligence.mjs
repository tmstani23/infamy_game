import assert from 'node:assert/strict';
import { createShinobiIntelligence, TARGET_MEMORY_TICKS } from '../src/sim/shinobi_intelligence.js';
import { contractMapLocation } from '../src/contract_map_marker.js';
const boss = { id: 'b', type: 'hero', owner: 'r', x: 10, z: 20, place: 'street' };
const crew = { id: 'c', type: 'thug', owner: 'r', x: 11, z: 20, place: 'street' };
const config = { sectors: {} };
const state = { tick: 0, clans: { p: { kind: 'ninja' }, r: { kind: 'yakuza' } }, entities: { b: boss, c: crew },
  deployment: { clans: { p: config } }, contracts: { active: { p: { id: 1, kind: 'boss', hero: 'b' } } }, businesses: { shop: { id: 'shop', x: 50, z: 60, room: 'room' } } };
let visible = false;
const vision = { canSee: () => visible }, game = { state, vision };
const intel = createShinobiIntelligence({ state, deployment: { sectorAt: () => 'nw' }, vision });
intel.tick(); assert.equal(config.bossTrack.discovered, false);
assert.equal(contractMapLocation(game, 'p'), null);
visible = true; intel.tick();
assert.equal(intel.targets('p').length, 2);
assert.deepEqual(contractMapLocation(game, 'p'), { x: 10, z: 20 });
visible = false; boss.x = 30; crew.x = 40; state.tick = 10; intel.tick();
assert.deepEqual(contractMapLocation(game, 'p'), { x: 30, z: 20 }, 'discovered nonstealth contract boss tracks outside vision');
assert.equal(config.targets.c.x, 11, 'crew never track outside vision');
assert.equal(config.targets.c.live, false);
boss.hidden = true; boss.x = 100; intel.tick();
assert.deepEqual(contractMapLocation(game, 'p'), { x: 30, z: 20 }, 'stealth freezes last known point');
boss.hidden = false; boss.x = 110; intel.tick();
assert.deepEqual(contractMapLocation(game, 'p'), { x: 30, z: 20 }, 'ending stealth still needs actual reacquisition');
visible = true; boss.place = 'room'; boss.x = 1000; boss.z = 1000; intel.tick();
assert.deepEqual(contractMapLocation(game, 'p'), { x: 50, z: 60 }, 'interior projects to building, not local coordinates');
visible = false; config.hunt = { target: 'c' }; state.tick = TARGET_MEMORY_TICKS + 20; intel.tick();
assert.ok(config.targets.c, 'armed target stays pinned beyond two minutes');
delete config.hunt; state.tick++; intel.tick();
assert.equal(config.targets.c, undefined, 'unpinned stale identity expires');
delete state.contracts.active.p; intel.tick(); assert.equal(config.bossTrack, undefined, 'contract end clears persistent tracking');
state.contracts.active.p = { id: 2, kind: 'steal', business: 'shop', target: 'r' }; intel.tick();
assert.equal(config.bossTrack, undefined, 'business contract never tracks rival boss');
assert.deepEqual(contractMapLocation(game, 'p'), { x: 50, z: 60 });
assert.doesNotThrow(() => JSON.stringify(state));
console.log('Shinobi intelligence: real sightings, 120-second memory/pins, boss-only discovery, unseen tracking, stealth/reacquisition, interiors and contract cleanup passed');
