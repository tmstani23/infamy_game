import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createGame } from '../src/sim/game.js';
import { setupMatch } from '../src/sim/setup_match.js';
const data=f=>JSON.parse(readFileSync(new URL(`../${f}`,import.meta.url)));
const g=createGame({district:data('data/port_town.json'),catalog:data('data/art.json'),cutouts:data('art/cutouts.json'),interiors:data('data/interiors.json'),parts:data('data/interior_parts.json'),recipes:data('data/room_recipes.json'),units:data('data/units.json')});
const {heroId}=setupMatch(g,{clan:'shinobi',difficulty:'easy',bots:data('data/bots.json')});
const h=g.state.entities[heroId],own=g.state.deployment.clans[h.owner],sector=g.state.deployment.sectors[0].id;
const send=c=>g.step([{id:heroId,type:'deployment',...c}]);
send({action:'assignment',sector,task:'ambush',request:'apply-1'});
assert.equal(own.sectors[sector].task,'ambush');assert.equal(own.feedback.ok,true);assert.equal(own.feedback.request,'apply-1');assert.match(own.feedback.text,/AMBUSH ACTIVE/);
const sequence=own.feedback.sequence;
send({action:'assignment',sector,task:'guard',request:'reject-1'});
assert.equal(own.feedback.ok,false);assert.equal(own.feedback.sequence,sequence+1);assert.equal(own.sectors[sector].task,'ambush','rejected order must not change duty');
send({action:'transfer',units:['not-your-crew'],to:sector,request:'transfer-1'});
assert.equal(own.feedback.ok,false);assert.equal(own.feedback.request,'transfer-1');
send({action:'armAmbush',sector,request:'arm-1'});assert.equal(own.feedback.ok,true);assert.equal(own.sectors[sector].ambushNext,true);
send({action:'cancelAmbush',sector,request:'cancel-1'});assert.equal(own.feedback.ok,true);assert.equal(own.sectors[sector].ambushNext,false);
assert.doesNotThrow(()=>JSON.stringify(g.state));
console.log('Deployment feedback: real accepted/rejected duties, invalid ownership, arm/cancel, request identity and serialized authoritative results passed');
