import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createGame} from '../src/sim/game.js';
import {setupMatch} from '../src/sim/setup_match.js';
const read=p=>JSON.parse(readFileSync(new URL(`../${p}`,import.meta.url)));
const g=createGame({district:read('data/port_town.json'),catalog:read('data/art.json'),cutouts:read('art/cutouts.json'),interiors:read('data/interiors.json'),parts:read('data/interior_parts.json'),recipes:read('data/room_recipes.json'),units:read('data/units.json')});
const {heroId}=setupMatch(g,{clan:'yakuza',difficulty:'easy',bots:read('data/bots.json')}),h=g.state.entities[heroId];
for(const e of Object.values(g.state.entities))e.holdFire=true;
const sector=g.state.deployment.sectors[0].id,crew=g.deployment.members(h.owner,'hero')[0];
const command=c=>g.step([{id:heroId,type:'deployment',...c}]);
command({action:'transfer',units:[crew.id],to:sector});assert.ok(crew.deployment.transfer);
for(let n=0;n<20;n++)g.step();
const position=[crew.x,crew.z];h.hitAt=g.state.tick;
command({action:'cancelTransfer',units:[crew.id]});assert.ok(crew.deployment.transfer.cancelled,'cancellation allowed during hero combat');
assert.equal(crew.deployment.transfer.to,'hero');assert.ok(Math.hypot(crew.x-position[0],crew.z-position[1])<1,'cancel never teleports');
for(let n=0;n<1200&&crew.deployment.transfer;n++)g.step();assert.equal(crew.deployment.transfer,undefined);assert.equal(crew.deployment.group,'hero');
h.hitAt=g.state.tick-120;command({action:'transfer',units:[crew.id],to:sector});
for(let n=0;n<6;n++)g.spawn('thug','thug',h.x+n*.1,h.z,{owner:h.owner,deployment:{group:'hero'},holdFire:true});
command({action:'cancelTransfer',units:[crew.id]});assert.equal(crew.deployment.transfer.to,'home','full original hero group falls back to unlimited HQ reserve');
assert.equal(crew.deployment.keepAtHQ,true,'cancelled HQ return cannot immediately auto-deploy again');
assert.equal(g.deployment.counts(h.owner).hero,6);
const rival=Object.values(g.state.entities).find(e=>e.owner!==h.owner&&e.type==='hero');
const before=structuredClone(crew.deployment.transfer);
g.step([{id:rival.id,type:'deployment',action:'cancelTransfer',units:[crew.id]}]);assert.equal(crew.deployment.transfer.to,before.to,'other clans cannot cancel your transfers');
assert.match(g.state.deployment.clans[rival.owner].feedback.text,/own crew/);
assert.doesNotThrow(()=>JSON.stringify(g.state));
console.log('Transfer cancellation: physical source return, combat cancellation, full-source HQ fallback/pin/cap and ownership passed');
