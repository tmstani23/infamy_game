import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createGame} from '../src/sim/game.js';
import {setupMatch} from '../src/sim/setup_match.js';
const read=p=>JSON.parse(readFileSync(new URL(`../${p}`,import.meta.url)));
const g=createGame({district:read('data/port_town.json'),catalog:read('data/art.json'),cutouts:read('art/cutouts.json'),interiors:read('data/interiors.json'),parts:read('data/interior_parts.json'),recipes:read('data/room_recipes.json'),units:read('data/units.json')});
const {heroId}=setupMatch(g,{clan:'yakuza',difficulty:'easy',bots:read('data/bots.json')}),sector=g.state.deployment.sectors[0];
for(const u of Object.values(g.state.entities))u.holdFire=true;
const e=g.state.entities[g.spawn('thug','thug',sector.anchor.x,sector.anchor.z,{owner:'player',deployment:{group:sector.id}})];
const grid=g.deployment.navFor(e),path=grid.findPath(e.x,e.z,...grid.nearestFree(e.x+10,e.z+5)),p=path.at(-1);
g.step([{id:heroId,type:'order',kind:'move',place:'street',units:[e.id],x:p[0],z:p[1]}]);
assert.equal(e.deployment.duty.manual,true);
const order=structuredClone(e.order);
g.step([{id:heroId,type:'deployment',action:'release',units:[e.id]}]);
assert.equal(e.deployment.duty.returnWhenDone,true);assert.equal(e.order.x,order.x);assert.equal(e.order.z,order.z);
for(let i=0;i<500&&e.deployment.duty.manual;i++)g.step();
assert.equal(e.deployment.duty.manual,false,'completed released move resumes saved duty');
assert.ok(Math.hypot(e.x-p[0],e.z-p[1])<3,'group switching must finish the confirmed move before returning');
g.step([{id:heroId,type:'order',kind:'move',place:'street',units:[e.id],x:sector.anchor.x,z:sector.anchor.z}]);
g.step([{id:heroId,type:'deployment',action:'return',units:[e.id],selectionChange:true}]);
assert.equal(e.deployment.duty.manual,false,'Escape cancels without waiting for arrival');
const other=g.state.deployment.sectors[1],f=g.state.entities[g.spawn('thug','thug',other.anchor.x,other.anchor.z,{owner:'player',deployment:{group:other.id},holdFire:true})];
const before=[e.order,f.order];
g.step([{id:heroId,type:'order',kind:'stop',units:[e.id,f.id]}]);
assert.notEqual(e.order.kind,'stop','mixed-group manual command cannot combine forces');
console.log('Manual release: confirmed move completes across selection switches, then duty; Escape immediate; mixed-group commands rejected');
