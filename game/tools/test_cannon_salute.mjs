// The governor's cannon salute (Tim 2026-11-07): 4 cannons and the Gatling (2026-11-10) by a player town hall, fired in turn
// on the first talk, after a tier upgrade and on "Fire a salute" (with a cooldown). Scenery: never hostile.
import assert from 'node:assert/strict';
import { createCannonSalute } from '../src/sim/cannon_salute.js';
const state = { tick: 0, entities: {}, casts: [], clans: { player: {}, bot: { bot: true } }, frontier: { settlements: {
  t1: { id: 't1', owner: 'player', founded: 0, x: 100, z: 100 }, t2: { id: 't2', owner: 'bot', founded: 0, x: 500, z: 500 } } } };
let n = 1;
const spawn = (type, model, x, z, extra) => { const id = String(n++); state.entities[id] = { id, type, model, x, z, ...extra }; return id; };
const removeUnit = id => delete state.entities[id];
const C = createCannonSalute({ state, spawn, removeUnit, cell: 11 });
const step = () => { state.casts = []; C.tick(); const out = state.casts; state.tick++; return out; };
step();
const t1 = state.frontier.settlements.t1;
assert.equal(t1.cannons.length, 5, 'four cannons and the Gatling by the hall');
assert.deepEqual(t1.cannons.map(id => state.entities[id].model), ['cannon_field', 'cannon_field', 'cannon_wooden', 'cannon_wooden', 'gatling']);
assert.ok(t1.cannons.every(id => state.entities[id].guide && !state.entities[id].owner), 'scenery: ownerless guides');
assert.ok(!state.frontier.settlements.t2.cannons, 'not for bots');
C.firstTalk(t1);
const shots = [];
const all = [];
for (let i = 0; i < 260; i++) for (const c of step()) all.push({ ...c, tick: state.tick - 1 });
for (const c of all) if (c.kind === 'cannonFire' || c.kind === 'gatlingFire') shots.push(c);
assert.equal(shots.length, 5, 'four shots, then the Gatling starts');
assert.deepEqual(shots.map(s => s.a), t1.cannons, 'one after another, brass first, Gatling last');
const burst = all.filter(c => c.kind === 'gatlingShot'), stop = all.filter(c => c.kind === 'gatlingStop');
assert.equal(burst.length, 30, '1 s of spin, then a shot every 2 ticks to the end of the 80-tick burst');
assert.equal(burst[0].tick - shots[4].tick, 20, 'first shot after 1 s of spin');
assert.equal(stop.length, 1, 'then one wind-down');
assert.equal(stop[0].tick - shots[4].tick, 80);
assert.ok(!state.entities[t1.cannons[4]].burst && state.entities[t1.cannons[4]].anim === 'idle', 'Gatling back to idle');
assert.equal(shots[1].tick - shots[0].tick, 16);
assert.ok(!t1.salute, 'finished');
C.firstTalk(t1); assert.ok(!t1.salute, 'only the first talk');
assert.equal(C.salute(t1, true), false, 'cooldown');
assert.match(state.clans.player.notice.text, /loaded/);
state.tick += 10 * 20;
assert.equal(C.salute(t1, true), true, 'asked after the cooldown');
for (let i = 0; i < 260; i++) step();
t1.tierUpAt = 5; step();
assert.ok(t1.salute, 'a tier upgrade fires a salute');
console.log('test_cannon_salute: ok');
